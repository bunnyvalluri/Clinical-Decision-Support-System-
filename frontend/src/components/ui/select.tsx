// Versatile Select supporting both Radix compound composition and classic options props
export interface NativeSelectProps
  extends React.SelectHTMLAttributes<HTMLSelectElement> {
  label?: string;
  error?: string;
  helperText?: string;
  options?: SelectOption[];
}

const NativeSelect = React.forwardRef<HTMLSelectElement, NativeSelectProps>(
  (
    { className, label, error, helperText, options, children, id, ...props },
    ref
  ) => {
    const selectId =
      id || (label ? label.toLowerCase().replace(/\s+/g, "-") : undefined);

    return (
      <div className="w-full space-y-1.5">
        {label && (
          <label
            htmlFor={selectId}
            className="block text-xs font-semibold text-foreground"
          >
            {label}
          </label>
        )}
        <div className="relative">
          <select
            id={selectId}
            ref={ref}
            className={cn(
              "flex h-9 w-full appearance-none rounded-md border border-input bg-background px-3 py-1 pr-9 text-sm text-foreground shadow-xs transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:cursor-not-allowed disabled:opacity-50",
              error && "border-destructive focus-visible:ring-destructive",
              className
            )}
            {...props}
          >
            {options
              ? options.map((opt) => (
                  <option
                    key={opt.value}
                    value={opt.value}
                    disabled={opt.disabled}
                    className="bg-background text-foreground"
                  >
                    {opt.label}
                  </option>
                ))
              : children}
          </select>
          <div className="pointer-events-none absolute right-3 top-1/2 -translate-y-1/2 text-muted-foreground">
            <ChevronDown className="h-4 w-4" />
          </div>
        </div>
        {error ? (
          <p className="text-xs text-destructive font-medium">{error}</p>
        ) : helperText ? (
          <p className="text-xs text-muted-foreground">{helperText}</p>
        ) : null}
      </div>
    );
  }
);
NativeSelect.displayName = "NativeSelect";

// Polymorphic Select Component
type DynamicSelectProps =
  | ({ options: SelectOption[]; label?: string; error?: string; helperText?: string } & React.SelectHTMLAttributes<HTMLSelectElement>)
  | (React.ComponentPropsWithoutRef<typeof SelectPrimitive.Root> & { options?: never; label?: string; error?: string; helperText?: string });

const Select = ((props: DynamicSelectProps) => {
  if ("options" in props && props.options !== undefined) {
    return <NativeSelect {...(props as NativeSelectProps)} />;
  }
  return <SelectPrimitive.Root {...(props as React.ComponentPropsWithoutRef<typeof SelectPrimitive.Root>)} />;
}) as React.FC<DynamicSelectProps> & {
  displayName?: string;
};
Select.displayName = "Select";

